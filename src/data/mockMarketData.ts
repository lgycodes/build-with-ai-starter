export function generateCandlestickData(basePrice: number, pointsCount = 36): CandlePoint[] {
  const points: CandlePoint[] = [];
  let currentClose = basePrice * 0.94;
  const now = new Date();

  for (let i = pointsCount - 1; i >= 0; i--) {
    const time = new Date(now.getTime() - i * 15 * 60 * 1000);
    const timeStr = time.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', hour12: false });

    const delta = (Math.random() - 0.48) * (basePrice * 0.014);
    const open = currentClose;
    const close = Math.max(basePrice * 0.4, open + delta);
    const high = Math.max(open, close) + Math.random() * (basePrice * 0.008);
    const low = Math.min(open, close) - Math.random() * (basePrice * 0.008);
    const volume = Math.floor(10000 + Math.random() * 85000);

    currentClose = close;
    points.push({ time: timeStr, open, high, low, close, volume });
  }

  // Anchor the last candle to the basePrice
  if (points.length > 0) {
    points[points.length - 1].close = basePrice;
  }

  return points;
}
